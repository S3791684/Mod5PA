# Uses loops to repeatedly explore Palmer Penguin statistics


import math

# constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"
NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

species_names = [SP_CHINSTRAP, SP_GENTOO, SP_ADELIE]
species_counts = [NUM_CHINSTRAP, NUM_GENTOO, NUM_ADELIE]


total_species = len(species_names)
total_penguins = sum(species_counts)
average_penguins = total_penguins / total_species
average_penguins_rounded_up = math.ceil(average_penguins)

chinstrap_percentage = species_counts[0] / total_penguins * 100
gentoo_percentage = species_counts[1] / total_penguins * 100
adelie_percentage = species_counts[2] / total_penguins * 100
species_percentages = [chinstrap_percentage, gentoo_percentage,
                       adelie_percentage]

largest_count = max(species_counts)
smallest_count = min(species_counts)
largest_index = species_counts.index(largest_count)
smallest_index = species_counts.index(smallest_count)
largest_species = species_names[largest_index]
smallest_species = species_names[smallest_index]

# output the species names with introductory text
print("Introducing the Palmer Penguins:\n")

print("\t" + SP_CHINSTRAP + "!")
print("\t" + SP_GENTOO + "!")
print("and last but not least...")
print("\t" + SP_ADELIE + "!")
print()
print(f"There are a total of {total_species} penguin species in the dataset.")
print(f"There are a total of {total_penguins} penguins in the dataset.")
print(f"The average number of penguins per species is {average_penguins:.1f}.")
print(f"The average rounded up is {average_penguins_rounded_up}.\n")

# For loop to display species statitistics
for index, species in enumerate(species_names):
    print(f"{species}: {species_counts[index]} "
          f"({species_percentages[index]:.2f}%)")

print("The species with the most observations is", SP_ADELIE, "with",
      NUM_ADELIE, "penguins.")
print("The species with the fewest observations is", SP_CHINSTRAP, "with",
      NUM_CHINSTRAP, "penguins.")
print("\n")

# Counter for valid species selections
valid_selections = 0

# Explore a species: Enter Chinstrap, Gentoo, Adelie, or Done
print("Explore a species:")
species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done:\n")

while species_choice != "Done":

  # Determine the Selected Species Index Using if, elif, and else
  if species_choice not in species_names:
    print(f"{species_choice} is not one of the species in this dataset")
  else:
    if species_choice == species_names[0]:
      selected_index = 0
    elif species_choice == species_names[1]:
      selected_index = 1
    elif species_choice == species_names[2]:
      selected_index = 2

# Retrieve the Selected Species Data
  selected_species = species_names[selected_index]
  selected_count = species_counts[selected_index]
  selected_percent = species_percentages[selected_index]
  valid_selections += 1

# Classify species by their percentage
  size_category = ""
  if selected_percent < 25:
    size_category = "small"
  elif (selected_percent >= 25) and (selected_percent < 40):
    size_category = "medium"
  else:
    size_category = "large"

  # Determine the Species' Relative Position
  position_description = ""

  if selected_species == largest_species:
    position_description = "largest"
  elif selected_species == smallest_species:
    position_description = "smallest"
  else:
    position_description = "middle-sized"

  # Compare the Selected Count to the Average
  if selected_count > average_penguins:
    average_position = "above"
  else:
    average_position = "below"

  print(
      f"{species_choice} has {selected_count} observations, "
      f"representing {selected_percent:.2f}% of the dataset."
  )

  print(f"{species_choice} is classified as a {size_category} species group.")
  print(f"{species_choice} is the {position_description} species group.")
  print(
      f"Its observation count is {average_position} the dataset average of "
      f"{average_penguins:.2f}"
  )
  species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done:\n")
print(f"You explored {valid_selections} valid species.")
print("Exploration complete.")





